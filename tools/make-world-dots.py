"""Rebuild data/world-dots.js, the dot-grid land map used by the travel map on beyond.html.

Downloads Natural Earth's 1:50m land outlines, draws them onto a fine grid, and writes
each row of land as "startColumn,length" runs.

Usage (from the project folder; needs Pillow: pip3 install pillow):
    python3 tools/make-world-dots.py            # 0.75 degree dots, the current setting
    python3 tools/make-world-dots.py --step 0.5 # finer dots, bigger file

After rebuilding, bump the ?v= number on data/world-dots.js in beyond.html so browsers reload it.
If you change --step a lot, also adjust the .map-land stroke-width in css/styles.css
(dot diameter is roughly half the spacing: 0.75 degree dots use 1.3).
"""

import argparse
import json
import urllib.request
from pathlib import Path

from PIL import Image, ImageDraw

LAND_URL = "https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_50m_land.geojson"
OUTPUT = Path(__file__).resolve().parent.parent / "data" / "world-dots.js"

LAT_TOP = 80     # northern edge of the map; js/beyond.js reads this from the output
LAT_BOTTOM = -60  # southern edge; Antarctica is left out
SUPERSAMPLE = 8   # each dot is drawn as an 8x8 block, then averaged
LAND_THRESHOLD = 90  # 0-255: how much of a cell must be land to get a dot (90 is about 35%)


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--step", type=float, default=0.75, help="degrees between dots (default 0.75)")
    step = parser.parse_args().step

    print("Downloading Natural Earth land outlines...")
    with urllib.request.urlopen(LAND_URL) as response:
        land = json.load(response)

    cols = round(360 / step)
    rows = round((LAT_TOP - LAT_BOTTOM) / step)
    canvas = Image.new("L", (cols * SUPERSAMPLE, rows * SUPERSAMPLE), 0)
    draw = ImageDraw.Draw(canvas)

    def to_pixel(lon, lat):
        return ((lon + 180) / step * SUPERSAMPLE, (LAT_TOP - lat) / step * SUPERSAMPLE)

    for feature in land["features"]:
        geometry = feature["geometry"]
        polygons = geometry["coordinates"] if geometry["type"] == "MultiPolygon" else [geometry["coordinates"]]
        for outline, *holes in polygons:
            draw.polygon([to_pixel(*point) for point in outline], fill=255)
            for hole in holes:  # lakes and inland seas
                draw.polygon([to_pixel(*point) for point in hole], fill=0)

    # Average each block down to one cell: the value is how much of that cell is land
    grid = canvas.resize((cols, rows), Image.BOX)

    lines = []
    for r in range(rows):
        runs = []
        c = 0
        while c < cols:
            if grid.getpixel((c, r)) < LAND_THRESHOLD:
                c += 1
                continue
            start = c
            while c < cols and grid.getpixel((c, r)) >= LAND_THRESHOLD:
                c += 1
            runs.append(f"{start},{c - start}")
        lines.append(" ".join(runs))
    while lines and not lines[-1]:
        lines.pop()

    rows_js = "\n".join(f'        "{line}",' for line in lines)
    OUTPUT.write_text(
        f"""/* Dot-matrix world map: land cells on a {step}° grid starting at {LAT_TOP}°N.
   Each row lists "startColumn,length" runs of land.
   Generated by tools/make-world-dots.py from Natural Earth 1:50m land polygons (equirectangular). */
const worldDots = {{
    step: {step},
    latTop: {LAT_TOP},
    rows: [
{rows_js}
    ],
}};
"""
    )
    print(f"Wrote {OUTPUT.name}: {len(lines)} rows, {OUTPUT.stat().st_size // 1024} KB")


if __name__ == "__main__":
    main()
